"""Seed loader: hand-authored CSVs in `seed/` -> dimension and reference tables.

Each CSV is MERGEd on its natural key, so re-running is idempotent and IDENTITY
surrogate keys stay stable. Rows are updated or inserted, never deleted. All seeds
load in one transaction, in FK-safe order. A seed can carry a natural value (e.g. an ISO3
code) that a lookup turns into a surrogate key; public holidays are generated by
`pipeline.calendar` rather than hand-authored.
"""

from __future__ import annotations

import csv
import logging
from dataclasses import dataclass
from pathlib import Path

from pipeline import calendar, config, db

log = logging.getLogger(__name__)


@dataclass(frozen=True)
class Lookup:
    """A CSV column holding a natural value, resolved to a surrogate key column on load."""

    csv_column: str
    target_column: str
    scalar_sql: str  # one `?` placeholder; must return exactly one value, or NULL fails NOT NULL


@dataclass(frozen=True)
class SeedSpec:
    csv_name: str
    table: str
    key: str
    columns: tuple[str, ...]  # allowed columns; the only names ever placed in SQL text
    lookups: tuple[Lookup, ...] = ()


