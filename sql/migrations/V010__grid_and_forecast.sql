-- V010: M3 hourly grid data, calendar and forecast tables (doc 05 §2.1-2.4; M3 plan Q1, Q2, Q6).
-- Constraint names follow the V004/V008 convention: pk_/fk_/df_/ck_/uq_<table>_...
-- No new grants: V005 grants are schema-wide, so these tables inherit them.

-- Generic interval landing table: an exact copy of each published file (Q1). file_name is the
-- published file name (e.g. system_2023.csv) and is part of the key, because consecutive files
-- repeat a boundary day; both copies are kept and stg proves they agree.
CREATE TABLE raw.grid_interval (
    grid_code    VARCHAR(20)    NOT NULL,
    file_name    VARCHAR(60)    NOT NULL,
    ts_text      VARCHAR(30)    NOT NULL,  -- timestamp exactly as the source wrote it
    series       VARCHAR(40)    NOT NULL,  -- source column name as published, e.g. north_demand, EDL_IMP
    value        DECIMAL(12, 2) NULL,      -- MW; NULL where the source cell is blank
    _run_id      BIGINT         NOT NULL CONSTRAINT fk_grid_interval_run REFERENCES meta.load_run (run_id),
    _source_file NVARCHAR(400)  NOT NULL,
    _loaded_at   DATETIME2(0)   NOT NULL CONSTRAINT df_grid_interval_loaded DEFAULT SYSUTCDATETIME(),
    CONSTRAINT pk_grid_interval PRIMARY KEY (grid_code, file_name, ts_text, series)
);

-- Public holidays from the pinned `holidays` package, written at seed time, plus any
-- hand-checked overrides (M3 plan step 3). Several holidays on one day share one row.
CREATE TABLE ref.public_holiday (
    country_code CHAR(2)       NOT NULL CONSTRAINT ck_public_holiday_country CHECK (country_code IN ('TH', 'MY')),
    holiday_date DATE          NOT NULL,
    name         NVARCHAR(300) NOT NULL,
    origin       VARCHAR(30)   NOT NULL,  -- e.g. 'holidays 0.105' or 'override'
    CONSTRAINT pk_public_holiday PRIMARY KEY (country_code, holiday_date)
);

CREATE TABLE dw.dim_hour (
    hour  TINYINT NOT NULL CONSTRAINT pk_dim_hour PRIMARY KEY CONSTRAINT ck_dim_hour_range CHECK (hour BETWEEN 0 AND 23),
    label CHAR(5) NOT NULL CONSTRAINT uq_dim_hour_label UNIQUE
);

-- Local calendar dates; generated by sql/transform/040_dim_date.sql. Upserted, never deleted,
-- because the forecast facts keep referencing old dates.
CREATE TABLE dw.dim_date (
    date_key      INT         NOT NULL CONSTRAINT pk_dim_date PRIMARY KEY,  -- yyyymmdd
    date          DATE        NOT NULL CONSTRAINT uq_dim_date_date UNIQUE,
    year          SMALLINT    NOT NULL CONSTRAINT fk_dim_date_year REFERENCES dw.dim_year (year),
    month         TINYINT     NOT NULL CONSTRAINT ck_dim_date_month CHECK (month BETWEEN 1 AND 12),
    month_name    CHAR(3)     NOT NULL,
    iso_weekday   TINYINT     NOT NULL CONSTRAINT ck_dim_date_weekday CHECK (iso_weekday BETWEEN 1 AND 7),
    is_weekend    BIT         NOT NULL,
    season_th     VARCHAR(10) NOT NULL CONSTRAINT ck_dim_date_season_th CHECK (season_th IN ('HOT', 'RAINY', 'COOL')),
    season_my     VARCHAR(12) NOT NULL CONSTRAINT ck_dim_date_season_my CHECK (season_my IN ('NE_MONSOON', 'SW_MONSOON', 'INTER')),
    is_holiday_th BIT         NOT NULL,
    is_holiday_my BIT         NOT NULL,
    CONSTRAINT ck_dim_date_key CHECK (date_key = YEAR(date) * 10000 + MONTH(date) * 100 + DAY(date))
);

CREATE TABLE dw.dim_grid (
    grid_key         INT IDENTITY(1, 1) NOT NULL CONSTRAINT pk_dim_grid PRIMARY KEY,
    grid_code        VARCHAR(20)   NOT NULL CONSTRAINT uq_dim_grid_code UNIQUE,
    name             NVARCHAR(80)  NOT NULL,
    country_key      INT           NOT NULL CONSTRAINT fk_dim_grid_country REFERENCES dw.dim_country (country_key),
    utc_offset_min   SMALLINT      NOT NULL CONSTRAINT ck_dim_grid_offset CHECK (utc_offset_min BETWEEN -720 AND 840),
    data_source_code VARCHAR(10)   NOT NULL CONSTRAINT fk_dim_grid_source REFERENCES dw.dim_data_source (data_source_code),
    is_published     BIT           NOT NULL CONSTRAINT df_dim_grid_published DEFAULT 0  -- consent gate (doc 03 P4)
);

-- Hourly system demand. Published hours only: no imputation in SQL (Q1). ts_text and
-- file_name point back to the raw row the value came from.
CREATE TABLE dw.fact_grid_hourly (
    grid_key   INT           NOT NULL CONSTRAINT fk_fgh_grid REFERENCES dw.dim_grid (grid_key),
    ts_utc     DATETIME2(0)  NOT NULL,
    ts_local   DATETIME2(0)  NOT NULL,
    demand_mw  DECIMAL(10, 1) NOT NULL CONSTRAINT ck_fgh_demand CHECK (demand_mw >= 0),
    is_imputed BIT           NOT NULL CONSTRAINT df_fgh_imputed DEFAULT 0,  -- kept for GSO; always 0 for Thailand
    date_key   INT           NOT NULL CONSTRAINT fk_fgh_date REFERENCES dw.dim_date (date_key),
    hour       TINYINT       NOT NULL CONSTRAINT fk_fgh_hour REFERENCES dw.dim_hour (hour),
    file_name  VARCHAR(60)   NOT NULL,
    ts_text    VARCHAR(30)   NOT NULL,
    CONSTRAINT pk_fact_grid_hourly PRIMARY KEY (grid_key, ts_utc),
    CONSTRAINT uq_fgh_local UNIQUE (grid_key, ts_local)
);

-- Cross-border flows per counterparty, from the grid's point of view (Thailand imports/exports).
-- A row exists only when the source filled at least one direction for that hour.
CREATE TABLE dw.fact_grid_flow_hourly (
    grid_key     INT            NOT NULL CONSTRAINT fk_fgfh_grid REFERENCES dw.dim_grid (grid_key),
    ts_utc       DATETIME2(0)   NOT NULL,
    counterparty VARCHAR(20)    NOT NULL CONSTRAINT ck_fgfh_counterparty CHECK (counterparty IN ('MY', 'LA_EDL', 'LA_HONGSA', 'KH')),
    ts_local     DATETIME2(0)   NOT NULL,
    import_mw    DECIMAL(10, 1) NULL,
    export_mw    DECIMAL(10, 1) NULL,
    date_key     INT            NOT NULL CONSTRAINT fk_fgfh_date REFERENCES dw.dim_date (date_key),
    hour         TINYINT        NOT NULL CONSTRAINT fk_fgfh_hour REFERENCES dw.dim_hour (hour),
    CONSTRAINT pk_fact_grid_flow_hourly PRIMARY KEY (grid_key, ts_utc, counterparty),
    CONSTRAINT ck_fgfh_some_value CHECK (import_mw IS NOT NULL OR export_mw IS NOT NULL)
);

-- One row per forecast run. run_kind separates development runs (2023 holdout), the single
-- locked FINAL 2024 backtest, and any labelled POST_HOC re-run (M3 plan, protocol #1, #12).
-- Runs are never deleted; is_current marks the one the report shows (one per grid).
CREATE TABLE dw.forecast_run (
    model_run_id        INT IDENTITY(1, 1) NOT NULL CONSTRAINT pk_forecast_run PRIMARY KEY,
    grid_key            INT            NOT NULL CONSTRAINT fk_forecast_run_grid REFERENCES dw.dim_grid (grid_key),
    load_run_id         BIGINT         NULL CONSTRAINT fk_forecast_run_load_run REFERENCES meta.load_run (run_id),
    run_kind            VARCHAR(10)    NOT NULL CONSTRAINT ck_forecast_run_kind CHECK (run_kind IN ('DEV', 'FINAL', 'POST_HOC')),
    trained_at          DATETIME2(0)   NOT NULL CONSTRAINT df_forecast_run_trained DEFAULT SYSUTCDATETIME(),
    model_name          VARCHAR(40)    NOT NULL,
    train_start         DATE           NOT NULL,
    train_end           DATE           NOT NULL,  -- of the last fold
    test_start          DATE           NOT NULL,
    test_end            DATE           NOT NULL,
    mape_model          DECIMAL(8, 3)  NULL,
    mape_baseline       DECIMAL(8, 3)  NULL,
    mae_model           DECIMAL(8, 3)  NULL,
    mae_baseline        DECIMAL(8, 3)  NULL,
    improvement_pct     DECIMAL(8, 3)  NULL,
    improvement_ci_low  DECIMAL(8, 3)  NULL,
    improvement_ci_high DECIMAL(8, 3)  NULL,
    scored_hours        INT            NULL,
    excluded_hours      INT            NULL,
    params_json         NVARCHAR(MAX)  NOT NULL CONSTRAINT ck_forecast_run_params CHECK (ISJSON(params_json) = 1),
    metrics_json        NVARCHAR(MAX)  NULL CONSTRAINT ck_forecast_run_metrics CHECK (metrics_json IS NULL OR ISJSON(metrics_json) = 1),
    git_commit          CHAR(40)       NULL,
    protocol_commit     CHAR(40)       NULL,
    is_current          BIT            NOT NULL CONSTRAINT df_forecast_run_current DEFAULT 0,
    CONSTRAINT ck_forecast_run_dates CHECK (train_start <= train_end AND train_end < test_start AND test_start <= test_end),
    CONSTRAINT ck_forecast_run_final CHECK (run_kind = 'DEV' OR protocol_commit IS NOT NULL)
);
CREATE UNIQUE INDEX uq_forecast_run_current ON dw.forecast_run (grid_key) WHERE is_current = 1;

CREATE TABLE dw.fact_load_forecast (
    model_run_id INT            NOT NULL CONSTRAINT fk_flf_run REFERENCES dw.forecast_run (model_run_id),
    grid_key     INT            NOT NULL CONSTRAINT fk_flf_grid REFERENCES dw.dim_grid (grid_key),
    ts_utc       DATETIME2(0)   NOT NULL,
    ts_local     DATETIME2(0)   NOT NULL,
    actual_mw    DECIMAL(10, 1) NULL,  -- NULL where the source has a gap
    forecast_mw  DECIMAL(10, 1) NOT NULL,
    baseline_mw  DECIMAL(10, 1) NULL,  -- NULL where t - 168 h is a gap
    is_scored    BIT            NOT NULL,  -- actual, model and baseline all present (protocol #5)
    date_key     INT            NOT NULL CONSTRAINT fk_flf_date REFERENCES dw.dim_date (date_key),
    hour         TINYINT        NOT NULL CONSTRAINT fk_flf_hour REFERENCES dw.dim_hour (hour),
    CONSTRAINT pk_fact_load_forecast PRIMARY KEY (model_run_id, grid_key, ts_utc)
);
